import type { MapLocation } from "../data/locations";

// In dev, Vite proxies /api to the backend (see vite.config.ts), so no CORS preflight is needed.
export const API_URL = import.meta.env.VITE_API_URL ?? "";

export interface WeatherSummary {
  current: {
    time: string;
    temperature: number | null;
    weather_code: number | null;
    is_day: boolean;
    wind_speed: number | null;
    precipitation_probability: number | null;
  };
  days: {
    date: string;
    temperature_min: number | null;
    temperature_max: number | null;
    weather_code: number | null;
    precipitation_probability: number | null;
  }[];
}

export interface LocationData {
  weather: WeatherSummary;
}

// Generated by backend/src/data/monument_geocode.py; kept out of the JS bundle.
export async function fetchMonuments(signal?: AbortSignal): Promise<MapLocation[]> {
  const response = await fetch(`${import.meta.env.BASE_URL}monuments.json`, { signal });

  if (!response.ok) {
    throw new Error(`Could not load monuments (${response.status})`);
  }

  return response.json();
}

export async function fetchLocationData(
  latitude: number,
  longitude: number,
  signal?: AbortSignal,
): Promise<LocationData> {
  const params = new URLSearchParams({
    lat: String(latitude),
    lon: String(longitude),
  });

  const response = await fetch(`${API_URL}/api/location?${params}`, { signal });

  if (!response.ok) {
    throw new Error(`Could not retrieve location data (${response.status})`);
  }

  return response.json();
}
